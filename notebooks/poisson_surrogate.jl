# ╔═╡ cb0918a8-8f86-45c1-aa1f-ddb26848a97e
md"""
## Opening the hood: the surrogate model

The cell above solved the model with RxInfer's **automatic** machinery: we
declared the `PoissonExp` leaves, added a mean-field + projection constraint,
and `infer` did everything. Below we rebuild the **same** inference *by hand*,
so you can see exactly what "project the Poisson leaf" means.

### Why plain Gaussian message passing fails

The latent chain $z_1 \to z_2 \to \dots$ is Gaussian, but every observation is a
Poisson count. The exact belief-propagation message a Poisson leaf sends back to
its edge $z_k$ is the log-likelihood

$$\ell_k(z_k) \;=\; \log \mathrm{Poisson}(y_k \mid e^{z_k}) \;=\; y_k\, z_k - e^{z_k} + \text{const}.$$

The $e^{z_k}$ makes this **not a parabola**, so it is not a Gaussian message and
Gaussian message passing cannot carry it unchanged.

### The surrogate leaf — the one idea to remember

Take the current Gaussian belief on the edge, $q_k = \mathcal N(m_k, v_k)$, and
**replace the Poisson leaf with the Gaussian message that best matches it there.**
Natural-gradient message passing tells us *which* Gaussian: the one whose
**natural parameters equal the gradient of $\mathbb E_{q_k}[\ell_k]$ in mean
coordinates**. With the only non-trivial moment $\rho_k = \mathbb E_{q_k}[e^{z_k}] = e^{m_k + v_k/2}$,

$$\underbrace{\xi_k = y_k + (m_k-1)\rho_k}_{\text{natural mean}}, \qquad \underbrace{\Lambda_k = \rho_k}_{\text{precision}},$$

i.e. a Gaussian message $\propto \exp\!\big(\xi_k z_k - \tfrac12 \Lambda_k z_k^2\big)$,
or equivalently a *fake observation* $\widetilde y_k = m_k + (y_k-\rho_k)/\rho_k$
with variance $R_k = 1/\Lambda_k$. We never type this formula by hand:
`poisson_surrogate` reads it straight from `ClosedWilliamsProduct` — the
closed-form Williams product of `PoissonExpression`, which returns exactly
$\nabla_{(m,\sigma)} \mathbb E_{q}[\ell]$.

### The outer loop (a fixed-point map)

Once every Poisson leaf is a Gaussian pseudo-observation, the graph is an
ordinary **normal–normal chain**, so a single `infer` on `lg_chain` runs exact
Gaussian smoothing (forward–backward). But the surrogate depends on the
marginal, which depends on the surrogate — so we iterate:

1. project every leaf at the current marginals $\to (\xi_k, \Lambda_k)$,
2. run **one** exact Gaussian BP sweep on the surrogate chain,
3. read the updated marginals, and repeat.

This is a fixed-point map $\lambda \leftarrow \Phi(\lambda)$; at a fixed point
the marginals stop changing.

### Damping and momentum

$\Phi$ need not be a contraction, so we take the step in natural-parameter space
with a damping factor `α` and **momentum** `β` (heavy-ball):

$$u \leftarrow \beta\,u + \alpha\big(\eta^\star - \eta\big), \qquad \eta \leftarrow \eta + u.$$

Momentum changes only the *path* to the solution, not the fixed point itself.

### This is **not** the same inference as the automatic run

The automatic run used `q(z) = MeanField()`, i.e. **mean-field variational
inference**: it forces the whole posterior to factorize, $q(z) = \prod_k q(z_k)$,
treating every state as independent. As is well known for mean-field, this
**does not estimate the variance correctly** — by assuming the states are
independent it throws away the temporal correlations, so the per-state
uncertainties it reports are off.

The surrogate model below keeps the chain **exact**: it replaces only the
Poisson leaves with Gaussian surrogates and then runs full forward–backward
Gaussian smoothing, so the joint covariance across time is preserved and the
posterior variances are the correct smoothed ones. This is the natural-gradient
message passing (NGMP) surrogate of §Surrogate Leaves; the paper contrasts it
with the mean-field route (VMP) in §VMP as the Classical Multi-Interface
Surrogate and §NGMP as the Improved Local Surrogate. The means come out close,
but the **uncertainty bands differ** — and that difference is the point.
"""

# ╔═╡ 2d3634c4-1b1b-42ab-bba9-0e0731f38af5
@model function lg_chain(y, R, σ, m0, v0)
    x[1] ~ Normal(mean = m0, variance = v0)
    y[1] ~ Normal(mean = x[1], variance = R[1])
    for k in 2:length(y)
        x[k] ~ Normal(mean = x[k-1], variance = σ)
        y[k] ~ Normal(mean = x[k],   variance = R[k])
    end
end

# ╔═╡ 0b00d09a-0422-4ac4-af57-1c4d7e278d8f
function poisson_surrogate(y::Real, m::Real, v::Real)
    ∂m, ∂σ = mean(
        ClosedWilliamsProduct(), 
        Logpdf(PoissonExpression(y)), 
        Normal(m, sqrt(v))
    )
    Λ = -∂σ / sqrt(v)
    ξ = ∂m + m * Λ
    return ξ, Λ
end

# ╔═╡ 11bded3d-294b-47c7-a29e-3a89b0c8bb76
function ngmp_poisson_smoother(y; σ = 0.1, m0 = 0.0, v0 = 10.0,
                               iters = 10, α = 0.5, β = 0.2)
    N = length(y)
    m = log.(y .+ 1.0); v = fill(1.0, N)          # initial edge marginals
    ξ = zeros(N); Λ = zeros(N)                     # surrogate message state η
    vξ = zeros(N); vΛ = zeros(N)                   # momentum buffers
    surrogate_free_energy = Float64[]              # Bethe FE of each frozen surrogate
    update_norm = Float64[]                        # fixed-point residual ‖Φ(λ)-λ‖∞
    local inference                                 # last inner BP result, kept below
    for _ in 1:iters
        s = poisson_surrogate.(y, m, v)            # project every leaf at q_k
        ηξ = first.(s); ηΛ = last.(s)
        @. vξ = β * vξ + α * (ηξ - ξ); @. ξ += vξ
        @. vΛ = β * vΛ + α * (ηΛ - Λ); @. Λ += vΛ
        inference = infer(
                     model = lg_chain(σ = σ, m0 = m0, v0 = v0),
                     data = (y = ξ ./ Λ, R = 1.0 ./ Λ),
                     options = (limit_stack_depth = 100,),
                     free_energy = true,
        )
        post = inference.posteriors[:x]
        mnew = mean.(post); vnew = var.(post)
        push!(surrogate_free_energy, inference.free_energy[end])
        push!(update_norm, max(maximum(abs.(mnew .- m)), maximum(abs.(vnew .- v))))
        m, v = mnew, vnew
    end
    return (inference = inference, means = m, variances = v,
            surrogate_free_energy = surrogate_free_energy, update_norm = update_norm)
end

# ╔═╡ af2b5341-66fe-4ff5-ad4b-bb7c4ab9b309
ngmp_result = ngmp_poisson_smoother(counts)

# ╔═╡ d1e2f3a4-0001-4b1c-9d2e-5f6a7b8c9d01
md"""
## Two more surrogates: the NGMP delta approximation and Laplace propagation

NGMP builds each leaf's Gaussian message from the **variance-aware** curvature
$-\mathbb E_q[\ell''] = e^{m+v/2}$ — the expected (Fisher) information, *averaged*
over the marginal $q=\mathcal N(m,v)$. Two classical surrogates are obtained by
peeling that apart along **two independent axes**: (i) *expected* vs *pointwise*
(observed) curvature, and (ii) expand at the **marginal mean** $m$ vs at the
**belief mode** $\hat z$.

| method | expand at | curvature | $\rho$ |
|:--|:--|:--|:--|
| **NGMP** | marginal mean $m$ | expected (Fisher) $-\mathbb E_q[\ell'']$ | $e^{m+v/2}$ |
| **NGMP delta-approx** | marginal mean $m$ | observed $-\ell''(m)$ | $e^{m}$ |
| **Laplace propagation** | belief **mode** $\hat z$ | observed $-\ell''(\hat z)$ | $e^{\hat z}$ |

**NGMP delta-approx.** Apply the quadratic delta approximation to $\ell$ about the
marginal *mean*: $\mathbb E_q[\ell'']\to\ell''(m)$, dropping the $e^{v/2}$ Fisher
factor. Same expansion point as NGMP, just the pointwise curvature. We read it off
the **same** `ClosedWilliamsProduct` evaluated at the deterministic point $z=m$
(zero variance), so the score collapses to $\partial_m=\ell'(m)=y-e^{m}$ and
$\Lambda=-\ell''(m)=y-\partial_m=e^{m}$.

**Laplace propagation** (Smola–Vishwanathan–Eskin, 2003) is the message-passing
form of the classical Laplace approximation: pin a Gaussian at the **mode of the
local belief** and read its width off the **pointwise Hessian** there. At edge
$z_k$ the recipe is literally:

1. Take the **incoming message** $\mu_{-}(z)=\mathcal N(z; m_-, 1/P_-)$ — the
   cavity, everything the chain sends *into* $z_k$ *except* the Poisson leaf.
2. Add the exact Poisson energy and find the **mode of the product**,
   ```math
   \hat z = \arg\max_z \Big[ -\tfrac{P_-}{2}(z-m_-)^2 \;+\; \underbrace{y\,z - e^{z}}_{\ell(z)} \Big],
   \qquad\text{i.e. solve}\quad P_-(m_- - z) + y - e^{z} = 0 .
   ```
3. Expand the leaf at that mode: precision $\Lambda=-\ell''(\hat z)=e^{\hat z}$,
   natural mean $\xi=\ell'(\hat z)+\hat z\,\Lambda$. Read off the **same**
   `ClosedWilliamsProduct` at the deterministic point $z=\hat z$.

The delta-approx is a *Laplace–Fisher hybrid* — observed curvature but expanded at
the **mean**, not the mode. It coincides with true Laplace only at a fixed point
where $m=\hat z$; the mode solve makes Laplace expand where the belief actually
peaks at every sweep.
"""

# ╔═╡ d1e2f3a4-0002-4b1c-9d2e-5f6a7b8c9d02
function ngmp_delta_surrogate(y::Real, m::Real, ::Real)  # third arg (variance) unused: delta uses the mean only
    # NGMP delta approximation: quadratic-delta of ℓ about the marginal MEAN m,
    # which drops the eᵛ/² Fisher factor (E_q[ℓ''] → ℓ''(m)). Same expansion point
    # as NGMP, observed curvature instead of expected. Evaluate the SAME Williams
    # product at the deterministic point z = m (zero variance): ∂m = ℓ'(m) = y−eᵐ.
    # (∂σ = −σ·eᵐ → 0 here, so NGMP's Λ = −∂σ/√v is 0/0 — recover Λ from the score.)
    ∂m, _ = mean(
        ClosedWilliamsProduct(),
        Logpdf(PoissonExpression(y)),
        Normal(m, 0.0),
    )
    Λ = y - ∂m            # −ℓ''(m) = eᵐ   (NGMP's ρ = eᵐ⁺ᵛ/² with the v/2 dropped)
    ξ = ∂m + m * Λ        # natural-mean parameter, exactly as in `poisson_surrogate`
    return ξ, Λ
end

# ╔═╡ d1e2f3a4-0003-4b1c-9d2e-5f6a7b8c9d03
function ngmp_delta_smoother(y; σ = 0.1, m0 = 0.0, v0 = 10.0,
                             iters = 10, α = 0.5, β = 0.2)
    N = length(y)
    m = log.(y .+ 1.0); v = fill(1.0, N)          # initial edge marginals
    ξ = zeros(N); Λ = zeros(N)                     # surrogate message state η
    vξ = zeros(N); vΛ = zeros(N)                   # momentum buffers
    surrogate_free_energy = Float64[]              # Bethe FE of each frozen surrogate
    update_norm = Float64[]                        # fixed-point residual ‖Φ(λ)-λ‖∞
    local inference                                 # last inner BP result, kept below
    for _ in 1:iters
        s = ngmp_delta_surrogate.(y, m, v)         # expand every leaf at the mean
        ηξ = first.(s); ηΛ = last.(s)
        @. vξ = β * vξ + α * (ηξ - ξ); @. ξ += vξ
        @. vΛ = β * vΛ + α * (ηΛ - Λ); @. Λ += vΛ
        inference = infer(
                     model = lg_chain(σ = σ, m0 = m0, v0 = v0),
                     data = (y = ξ ./ Λ, R = 1.0 ./ Λ),
                     options = (limit_stack_depth = 100,),
                     free_energy = true,
        )
        post = inference.posteriors[:x]
        mnew = mean.(post); vnew = var.(post)
        push!(surrogate_free_energy, inference.free_energy[end])
        push!(update_norm, max(maximum(abs.(mnew .- m)), maximum(abs.(vnew .- v))))
