md"""
# Inferring a hidden rate from count data

**The setting.** We observe a long sequence of **counts** — one integer per time
step — generated by a *rate* that we believe drifts slowly and smoothly. The job
is to recover that hidden rate, with uncertainty, from the noisy counts: denoise
the data and reveal the underlying signal.

**The dataset.** `Sunspots()` loads the classic monthly **sunspot numbers** — how
many sunspots were counted on the Sun each month, recorded for more than two
centuries (over 3000 months). They rise and fall with the famous ~11-year solar
cycle on top of heavy month-to-month noise, and they are non-negative integers
$y_k$ — exactly the kind of data a Poisson model is built for.

**The model (a Poisson state-space model).** Each count is Poisson with a
time-varying rate, $y_k \sim \mathrm{Poisson}(\lambda_k)$. To keep the rate
positive and let it wander smoothly, we track its **log-rate**
$z_k = \log \lambda_k$ and let it follow a Gaussian random walk,
$z_k = z_{k-1} + \text{noise}$. So a slowly drifting latent $z_k$ produces the
bursty counts we observe; inference asks: given the counts, what was the log-rate
each month, and how sure are we?

**Why it isn't trivial — and what this notebook shows.** The random walk is
Gaussian and easy; the trouble is the Poisson observation, which is **not
conjugate** to the Gaussian state, so ordinary Gaussian message passing stalls at
each observation. We solve the *same model* **four** ways and compare them:

1. **CVI with mean-field (RxInfer, automatic).** Declare the model, add a
   mean-field + projection constraint, and let `infer` run conjugate-computation
   variational inference.
2. **NGMP (by hand).** Replace each Poisson leaf with a tailored Gaussian
   stand-in built from the closed-form **natural-gradient** message — the
   curvature averaged over the cavity, $\rho = e^{m+v/2}$ — then run exact
   Gaussian smoothing and iterate.
3. **NGMP delta-approximation (by hand).** The same loop, expanding at the mean
   but with the *pointwise* curvature $e^{m}$ — NGMP with the $e^{v/2}$ Fisher
   correction dropped.
4. **Laplace propagation (by hand).** The classical Laplace approximation as
   message passing: find the **mode** of each leaf's local belief
   (incoming message × Poisson energy) and expand the pointwise curvature
   $e^{\hat z}$ *there*.

The four agree on the trend but differ in the **uncertainty** they report, which
is the lesson of the comparison.
"""

