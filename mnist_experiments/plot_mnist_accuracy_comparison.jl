function accuracy_plot(
    rx_vector,
    rx_nesterov,
    rx_two_hidden_vector,
    rx_two_hidden_nesterov,
    neural_depth,
    neural_cnn,
    rx_cnn_vector;
    title,
)
    neural_colors = [
        :darkorange, :goldenrod3, :sienna3, :mediumpurple3,
        :slateblue3, :deepskyblue3, :teal,
    ]
    neural_styles = [:solid, :dash, :dot, :dashdot, :solid, :dash, :dot]
    plot(
        1:length(neural_depth[1]), neural_depth[1];
        label = "Neural MLP (1 hidden)",
        color = neural_colors[1],
        linewidth = 2.5,
        linestyle = neural_styles[1],
        xlabel = "Epoch",
        ylabel = "Accuracy",
        title,
        xlims = (1, 50),
        ylims = (0.0, 1.0),
        yticks = 0.0:0.1:1.0,
        legend = :outerright,
        grid = true,
        minorgrid = true,
        size = (1350, 650),
        dpi = 160,
        left_margin = 5Plots.mm,
        bottom_margin = 5Plots.mm,
    )
    for depth in 2:length(neural_depth)
        plot!(
            1:length(neural_depth[depth]), neural_depth[depth];
            label = "Neural MLP ($depth hidden)",
            color = neural_colors[depth],
            linewidth = 2.5,
            linestyle = neural_styles[depth],
            marker = :none,
        )
    end
    plot!(
        1:length(neural_cnn), neural_cnn;
        label = "Neural categorical CNN",
        color = :firebrick3,
        linewidth = 2.5,
        linestyle = :dash,
        marker = :none,
    )
    plot!(
        1:length(rx_vector), rx_vector;
        label = "RxInfer MLP (vector transport)",
        color = :dodgerblue3,
        linewidth = 3,
        marker = :circle,
        markersize = 5,
    )
    plot!(
        1:length(rx_nesterov), rx_nesterov;
        label = "RxInfer MLP (projected Nesterov)",
        color = :black,
        linewidth = 3,
        linestyle = :dash,
        marker = :utriangle,
        markersize = 5,
    )
    plot!(
        1:length(rx_two_hidden_vector), rx_two_hidden_vector;
        label = "RxInfer 2-hidden MLP (vector transport)",
        color = :deeppink3,
        linewidth = 3,
        marker = :xcross,
        markersize = 6,
    )
    plot!(
        1:length(rx_two_hidden_nesterov), rx_two_hidden_nesterov;
        label = "RxInfer 2-hidden MLP (projected Nesterov)",
        color = :seagreen4,
        linewidth = 3,
        marker = :diamond,
        markersize = 5,
    )
    plot!(
        1:length(rx_cnn_vector), rx_cnn_vector;
        label = "RxInfer CNN-like (vector transport)",
        color = :purple3,
        linewidth = 3,
        marker = :star5,
        markersize = 7,
    )
end

