function accuracy_plot(one_hidden, two_hidden, neural_depth; title)
    plot(
        1:length(one_hidden), one_hidden;
        label = "RxInfer MLP (1 hidden, vector transport)",
        color = :dodgerblue3,
        linewidth = 3,
        marker = :circle,
        markersize = 4,
        xlabel = "Epoch",
        ylabel = "Accuracy",
        title,
        xlims = (1, 50),
        ylims = (0.0, 1.0),
        yticks = 0.0:0.1:1.0,
        legend = :outerright,
        grid = true,
        minorgrid = true,
        size = (1050, 650),
        dpi = 160,
        left_margin = 5Plots.mm,
        bottom_margin = 5Plots.mm,
    )
    plot!(
        1:length(two_hidden), two_hidden;
        label = "RxInfer MLP (2 hidden, vector transport)",
        color = :deeppink3,
        linewidth = 3,
        marker = :xcross,
        markersize = 5,
    )
    neural_colors = [:darkorange, :goldenrod3, :sienna3, :mediumpurple3, :slateblue3, :teal, :firebrick3]
    neural_styles = [:solid, :dash, :dot, :dashdot, :solid, :dash, :dot]
    for depth in eachindex(neural_depth)
        plot!(
            1:length(neural_depth[depth]), neural_depth[depth];
            label = "Neural MLP ($depth hidden)",
            color = neural_colors[depth],
            linewidth = 2.2,
            linestyle = neural_styles[depth],
        )
    end
    return current()
end

